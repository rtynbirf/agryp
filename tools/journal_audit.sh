#!/bin/sh
# Аудитор цепи печатей журнала agryp (Виток 10, тикет 013).
#
# Каждая ротация кладёт в НОВЫЙ журнал первой строкой реестр-печать:
#   {"event":"rotate",...,"seal":"<sha256 всего отрезанного хвоста>"}
# Файл-хвост .k запечатан первой строкой файла .k-1 (или текущего журнала
# для .1): когда хвост отрезали, печать стала первой строкой нового
# текущего журнала; после следующих ротаций он сам уехал на позицию выше.
# Подделка ЛЮБОГО байта (включая середину) меняет sha256 — аудитора ловит
# с точным приговором (Ст. 6: журнал не лжёт).
#
# usage: tools/journal_audit.sh <dir>
# Код выхода: 0 — цепь цела; 1 — подделка/дыра; 2 — неверный вызов.
set -u

[ $# -eq 1 ] || { echo "usage: $0 <dir>" >&2; exit 2; }
dir=$1
base="$dir/.agryp-journal.ndjson"
[ -f "$base" ] || { echo ">> АУДИТ ПРОВАЛЕН: журнала $base нет"; exit 1; }

fail=0
k=1
while [ "$k" -le 3 ]; do
    tailf="$base.$k"
    [ -f "$tailf" ] || { k=$((k+1)); continue; }
    sealer="$base.$((k-1))"
    [ "$k" -eq 1 ] && sealer="$base"
    if [ ! -f "$sealer" ]; then
        echo ">> АУДИТ ПРОВАЛЕН: хвост $tailf есть, а печатающего журнала $sealer нет — дыра в цепи"
        fail=1
        k=$((k+1)); continue
    fi
    seal=$(head -1 "$sealer" | sed -n 's/.*"seal":"\([0-9a-f]\{64\}\)".*/\1/p')
    if [ -z "$seal" ]; then
        echo ">> АУДИТ ПРОВАЛЕН: в $sealer первой строки-печати нет — хвост $tailf никто не запечатал"
        fail=1
        k=$((k+1)); continue
    fi
    actual=$(sha256sum "$tailf" | cut -d' ' -f1)
    if [ "$seal" = "$actual" ]; then
        echo ">> пломба сошлась: $tailf = $seal"
    else
        echo ">> АУДИТ ПРОВАЛЕН: ПОДДЕЛКА в $tailf: печать $seal, факт sha256 $actual — журнал лжёт"
        fail=1
    fi
    k=$((k+1))
done

[ "$fail" -eq 0 ] && echo ">> цепь печатей цела: журнал не лжёт"
exit $fail
